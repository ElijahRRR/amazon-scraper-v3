# ASCII-only 折叠函数。**不要**用 lower()/ILIKE：它们折叠全 Unicode，
# 而 SQLite 的 LIKE 与 FTS5 trigram 只折叠 ASCII（实测 'CAFÉ CREME' 不匹配
# '%café%'）。IMMUTABLE + 与 collation 无关，所以能进表达式索引。
ASCII_LOWER_FN = """
CREATE OR REPLACE FUNCTION public.ascii_lower(t text)
RETURNS text
LANGUAGE sql IMMUTABLE PARALLEL SAFE STRICT
AS $fn$
  SELECT translate($1, 'ABCDEFGHIJKLMNOPQRSTUVWXYZ', 'abcdefghijklmnopqrstuvwxyz')
$fn$;
"""

