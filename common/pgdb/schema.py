class SchemaMixin:
    """DDL。只依赖 PoolMixin 提供的 ``self._db`` / ``self._pool``。"""

    async def init_tables(self):
        """建表建索引。幂等：可以对着已有库反复跑。

        每条语句独立自动提交（不裹在一个事务里）——这是刻意的：
        SQLite 版靠 isolation_level=None 让每条 DDL 单独提交，PG 里若裹成一个
        事务，任何一条失败都会让后面全部 ``InFailedSQLTransactionError``。
        """
        conn = self._write_conn
        if conn is None:
            raise RuntimeError("init_tables 需要已建立的写连接")

        # pg_trgm + ascii_lower：需要建扩展的权限。生产角色若没有，
        # 把这两步挪到独立的 bootstrap 脚本，init_tables 只管假设它已就绪。
        try:
            await conn.execute("CREATE EXTENSION IF NOT EXISTS pg_trgm")
        except Exception as e:  # noqa: BLE001
            logger.warning("pg_trgm 扩展创建失败（搜索会退化成顺序扫描）: %s", e)
        await conn.execute(ASCII_LOWER_FN)

        for stmt in DDL_TABLES:
            await conn.execute(stmt)
        for stmt in DDL_INDEXES:
            await conn.execute(stmt)
        for stmt in DDL_TRGM_INDEXES:
            try:
                await conn.execute(stmt)
            except Exception as e:  # noqa: BLE001
                # 与 SQLite 版一致：搜索索引建不出来只告警，不挡启动
                logger.warning("trgm 索引初始化异常（不影响核心功能）: %s", e)

        try:
            tag = await conn.execute(BACKFILL_LEGACY_BATCHES)
            n = int(str(tag).rsplit(" ", 1)[-1])
            if n > 0:
                logger.info("数据库迁移: 回填 %d 个老批次为 completed", n)
        except Exception as e:  # noqa: BLE001
            logger.warning("老批次 backfill 异常: %s", e)

    async def verify_schema(self, strict: bool = True) -> List[str]:
        """比对实际列序与 EXPECTED_COLUMNS。返回问题列表（空 = 一致）。

        存在的理由：``SELECT d.*`` 没有 response_model，任何多出来/少掉/换位的列
        都会直接改变 erpAPI 看到的响应。把"永远别给 asin_data 加列"从注释
        升级成硬闸门。
        """
        conn = self._write_conn
        problems: List[str] = []
        for table, expected in EXPECTED_COLUMNS.items():
            rows = await conn.fetch(
                "SELECT column_name FROM information_schema.columns "
                "WHERE table_schema='public' AND table_name=$1 "
                "ORDER BY ordinal_position", table)
            actual = [r["column_name"] for r in rows]
            if actual != expected:
                problems.append(
                    f"{table}: 列序/列集不符\n  期望={expected}\n  实际={actual}")
        if problems and strict:
            raise RuntimeError("PG schema 与 SQLite 基线不一致:\n" + "\n".join(problems))
        return problems

    async def reset_all(self):
        """清空全部业务表并把 identity 重置回 1（测试夹具用）。

        与 `DELETE /api/database` 的语义一致：不动 seller_discoveries 之外的
        取舍见 CLEARED_TABLES 注释。这里为了测试可重复性把它也一并清掉。
        """
        conn = self._write_conn
        await conn.execute(
            "TRUNCATE asin_changes, asin_data, batch_asins, tasks, "
            "screenshots, batches, seller_discoveries RESTART IDENTITY")
