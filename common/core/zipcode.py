"""common/core/zipcode.py —— 邮编「补零规则」的唯一真源。

**这里只有补零这一条规则，没有别的。** 仓库里有**四份**邮编归一化，
Phase 4.6 刻意**不合并**它们（各有成文理由，见下），只把它们**共同的**
那一小步抽出来：

    纯数字且短于 5 位 -> 左补零到 5 位

------------------------------------------------------------------------
为什么补零这一步必须共享
------------------------------------------------------------------------
``common/pgdb/relay.py:normalize_zip_observed`` 的 docstring 本来就写着：

    「补零规则与 ``normalize_zip`` **必须一致**：这两个值会被
     ``reconcile_zip_verify`` 直接比较，一边补零一边不补，就会凭空造出
     ``mismatch``（'01001' vs '1001'）。」

在 4.6 之前那是一条**只写在注释里的**约束 —— 两份实现各自抄了一遍
``s.isdigit() and 0 < len(s) < 5``，谁改一边都没有任何东西会响。
本模块把那条注释变成可执行的：两边现在调同一个函数。

同一条规则的第三个用户是 ``server/app.py:_normalize_zip``。
它是 ``/api/tasks/pull`` 的 ``prefer_zip`` 归一入口（Phase 4.6 之后），
补的零最终会去和 relay 归一出来的 ``zip_requested`` 比对，
所以它和上面两份**必须**同规则，理由和上面那段一模一样。

------------------------------------------------------------------------
⚠ 不要把外层的四个函数合并进来
------------------------------------------------------------------------
它们的**外层语义各不相同**，合并会静默改行为：

* ``server/app.py:_normalize_zip`` —— 整串校验 + Excel 修复（``90001.0``）+
  ZIP+4 取前段；不合法回 ``None``。
* ``common/pgdb/relay.py:normalize_zip`` —— **原样透传**。不认识的形状宁可原样
  留着，也不要自作主张把一个商品的价格序列劈成两组（它是分组键的一部分）。
* ``common/pgdb/relay.py:normalize_zip_observed`` —— 同上，但 ``None`` 是**合法且
  常见**的返回（页面没挂 glow 挂件），且额外拦 bool / list / dict。
* ``worker/parser.py:_norm_zip`` —— **串内抽取**：补零规则不适用时还会
  ``_ZIP5_RE.search(s)`` 从任意串里捞一个 5 位数出来。
  它的数字分支写的是 ``0 < len(head) <= 5``（比这里多允许 ``== 5``），
  而 ``"12345".zfill(5) == "12345"`` ⇒ **结果完全一致**，只是它没法直接用本函数的
  「不适用就回 None」形状，改写它属于动 worker 侧解析逻辑（C3 / D-27），
  4.6 **不做**，只在那边留一条反向指针。

本模块只依赖 typing（标准库），不牵扯任何数据库驱动，worker 侧 import 它是安全的。
（原文写的是「零依赖，不 import 任何东西」—— 不实，Phase 4.5-4.8 审计指出。
同包的 completeness.py 才是真的 import 语句数为 0。）
"""
from typing import Optional


def _zfill_short_numeric(s: str) -> Optional[str]:
    """``s`` 若是「纯数字且短于 5 位」，回左补零到 5 位的结果；否则回 ``None``。

    ``None`` 的意思是 **「补零这条规则不适用」**，不是「无效邮编」——
    有效性判定是各调用方外层的事，这里一个字都不管。

    为什么下界写 ``0 < len(s)``：``"".isdigit()`` 本来就是 ``False``，
    这个下界是冗余的**文档**，写出来是为了让「空串不补零」是一条读得见的规则，
    而不是一条依赖 ``str.isdigit`` 实现细节的巧合。

    为什么上界是 ``< 5`` 而不是 ``<= 5``：5 位数字补零是恒等变换，
    把它算进「适用」会让调用方分不清「补过了」和「本来就对」——
    而 relay 的两个调用方要拿这个区别去计 ``zip_coerced``。
    """
    if s.isdigit() and 0 < len(s) < 5:
        return s.zfill(5)
    return None


__all__ = ["_zfill_short_numeric"]
