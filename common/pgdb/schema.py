"""common/pgdb/schema.py —— PostgreSQL 侧的完整 DDL。

OWNS:
    init_tables()          —— 幂等，可反复执行
    verify_schema()        —— 断言列集与列序，与 SQLite 新库逐列比对
    reset_all()            —— 测试/清库用（TRUNCATE ... RESTART IDENTITY）

--------------------------------------------------------------------------
类型决策（已定，不要推翻）
--------------------------------------------------------------------------
* 时间戳一律 ``text``，格式 ``'%Y-%m-%d %H:%M:%S'``，**不是** timestamptz。
  硬证据：server/app.py:1168 与 487 对该值做 ``datetime.strptime(x[:19], ...)``，
  datetime 对象不可下标 → TypeError；而且 asyncpg 会把 timestamptz 还成
  datetime，FastAPI 再序列化成 ISO-8601，erpAPI 拿到的每一条 created_at/
  updated_at 都变形。
  ⚠ ``DEFAULT CURRENT_TIMESTAMP`` 在 PG 的 text 列上**不会报错**，但会存成
  ``'2026-08-04 20:25:57.851686+00'``（带微秒和时区偏移）——静默变形。
  所以默认值一律写 ``to_char(clock_timestamp() AT TIME ZONE 'UTC', ...)``。
  用 clock_timestamp() 而不是 now()：SQLite 的 CURRENT_TIMESTAMP 在同一个事务里
  会往前走，now() 冻在事务开始时刻。
* 布尔一律 ``integer`` 0/1，**不是** boolean。
  ``/api/batches`` 的 needs_screenshot 在基线里是 int ``0``，而
  ``/api/tasks/pull`` 的同名字段是 ``false``（因为 database.py:1222 显式
  ``bool()`` 了一次）。同一个逻辑布尔在 API 上有两种形状，两种都被钉死了。
* id 一律 ``bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY``。
  实测：identity + ON CONFLICT DO NOTHING 与 SQLite AUTOINCREMENT + INSERT OR
  IGNORE **烧号方式完全一致**（插 a,b,c 再插 a,b,c 再插 d,e → 1,2,3,7,8）。
  基线钉死了这些空洞：golden_batch_b 的 id 是 3 不是 2，task id 是 1,3,7,8。
  → 绝不允许"先 SELECT 再 INSERT" / "WHERE NOT EXISTS" 之类的预过滤优化。
  用 BY DEFAULT 而非 ALWAYS：ALWAYS 会挡住将来的显式 id 回填。
* 所有 text 列都带 ``COLLATE "C"``。
  SQLite 的 TEXT 比较是 BINARY（字节序）。scraper_dev 恰好是 C.UTF-8 所以现在
  看不出问题，但生产库若用 en_US.UTF-8 建，``iter_results`` 的 keyset 游标
  （``ba.asin > $n ORDER BY ba.asin``）会重排导出行序、``updated_at < cutoff``
  的回收判定也会漂。逐列 COLLATE "C" 能扛住"恢复到另一台 collation 不同的库"。

--------------------------------------------------------------------------
不移植的东西
--------------------------------------------------------------------------
* 13 条 PRAGMA、WAL、只读连接池 —— 见 pool.py / admin.py。
* database.py:609-717 的 27 条 ``ALTER TABLE ... except: pass`` 迁移阶梯 ——
  **不移植**。它在新库上全是死代码（列都已在 CREATE TABLE 里），而在 PG 里
  一旦落进事务，第一条失败就会让后续全部 ``InFailedSQLTransactionError``，
  再被裸 except 吞掉 → 半张表悄悄建不出来。这里直接一次性建全列。
  代价是列序必须手工对齐 SQLite 新库的物理列序（``SELECT d.*`` 无
  response_model，列集会整个泄进 erpAPI 的响应），verify_schema() 负责守住。
* FTS5 虚表 + 3 个触发器 + rebuild 探针 —— 换成 pg_trgm 的 3 个表达式 GIN 索引。
"""
